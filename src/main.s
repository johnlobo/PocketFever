;;-----------------------------------------------------------------
;;
;; _main
;;
;;  Disable firmware, Mode 0, palette, font, then idle.
;;  Input:
;;  Output: Does not return
;;  Modified: AF, BC, DE, HL, IX, IY
;;
_main::
    ld hl, #transparency_table_src
    ld de, #transparency_table
    ld bc, #256
    ldir

    call sys_system_disable_firmware

    ld c, #0
    call cpct_setVideoMode_asm

    ld hl, #_g_palette0
    ld de, #16
    call cpct_setPalette_asm

    call sys_render_clear_front_buffer

    ld hl, #_s_font_0
    call sys_text_init
    call sys_messages_init

    call game_table_init

    call sys_physics_init
    call sys_collision_init

    cpctm_screenPtr_asm de, 0xC000, 0, HUD_Y_PX+2
    ld hl, #_game_version_string
    ld c, #0
    call sys_text_draw_string

    cpctm_screenPtr_asm de, 0xC000, 0, HUD_Y_PX+20
    ld hl, #shot_hint_string
    ld c, #0
    call sys_text_draw_string

;; PROFILE_RASTER (config.h.s) paints the border one colour per phase, so a
;; screenshot shows how many raster lines each phase takes.
.macro ProfileBorder _hw
.if PROFILE_RASTER
    ld hl, #(_hw)*256+16
    call cpct_setPALColour_asm
.endif
.endm

;; Erase + draw run right after VSYNC, while the beam is still in the top
;; border/HUD. Physics + collision take ~14 ms; between erase and draw they
;; kept the balls off screen for the whole felt scan.
loop:
    ProfileBorder HW_BLACK
    call cpct_waitVSYNC_asm
    ProfileBorder HW_BRIGHT_RED
    call sys_entity_erase_all
    call sys_entity_draw_all
    call game_shot_update
    ProfileBorder HW_BRIGHT_YELLOW
    call sys_physics_update
    ProfileBorder HW_BRIGHT_WHITE
    call sys_collision_update
    ld hl, (game_loop_count)
    inc hl
    ld (game_loop_count), hl
    jr loop
